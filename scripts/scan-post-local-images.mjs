#!/usr/bin/env node
/**
 * Scans public/mock/posts for image files and writes manifest.
 * Sources:
 *   1) public/mock/posts/강남_{NNN}.ext       → POST_LOCAL_IMAGE_POOL_GANGNAM
 *   2) public/mock/posts/광화문_{NNN}.ext      → POST_LOCAL_IMAGE_POOL_GWANGHWAMUN (legacy)
 *   3) public/mock/posts/seoul/Gwanghwamun/*  → POST_LOCAL_IMAGE_POOL_GWANGHWAMUN (ASCII)
 */
import fs from "node:fs";
import path from "node:path";

const ROOT = process.cwd();
const DIR = path.join(ROOT, "public/mock/posts");
const GWANGHWAMUN_SUBDIR = path.join(DIR, "seoul/Gwanghwamun");
const OUT = path.join(ROOT, "src/data/post-local-images-manifest.gen.ts");

const ROOT_RE = /^(강남|광화문)_(\d+)\.[^.]+$/u;
const IMAGE_EXT_RE = /\.(jpg|jpeg|png|avif|webp)$/i;

function main() {
  if (!fs.existsSync(DIR)) fs.mkdirSync(DIR, { recursive: true });

  // ── 1) Root pool: 강남 & 광화문 legacy ──────────────────────────────────────
  const files = fs.existsSync(DIR) ? fs.readdirSync(DIR) : [];
  const byLogical = new Map();

  for (const file of files) {
    const stat = fs.statSync(path.join(DIR, file));
    if (!stat.isFile()) continue;
    const nfc = file.normalize("NFC");
    const m = nfc.match(ROOT_RE);
    if (!m) continue;
    const region = m[1];
    const num = parseInt(m[2], 10);
    const key = `${region}_${String(num).padStart(3, "0")}`;
    if (!byLogical.has(key)) byLogical.set(key, { region, num, file });
  }

  const gangnam = [];
  const gwanghwamunLegacy = [];
  for (const { region, num, file } of byLogical.values()) {
    const url = `/mock/posts/${file}`;
    if (region === "강남") gangnam.push({ num, url });
    else gwanghwamunLegacy.push({ num, url });
  }
  gangnam.sort((a, b) => a.num - b.num);
  gwanghwamunLegacy.sort((a, b) => a.num - b.num);

  // ── 2) Gwanghwamun ASCII subdirectory ────────────────────────────────────────
  const gwanghwamunAscii = [];
  if (fs.existsSync(GWANGHWAMUN_SUBDIR)) {
    const subFiles = fs.readdirSync(GWANGHWAMUN_SUBDIR).sort();
    for (const file of subFiles) {
      if (file.startsWith(".")) continue;
      const fullPath = path.join(GWANGHWAMUN_SUBDIR, file);
      if (!fs.statSync(fullPath).isFile()) continue;
      if (!IMAGE_EXT_RE.test(file)) continue;
      gwanghwamunAscii.push(`/mock/posts/seoul/Gwanghwamun/${file}`);
    }
  }

  // ── Merge: ASCII first (preferred), then legacy ───────────────────────────────
  const gwanghwamunAll = [
    ...gwanghwamunAscii,
    ...gwanghwamunLegacy.map((x) => x.url),
  ];

  const body = `/* eslint-disable */
/* Auto-generated by scripts/scan-post-local-images.mjs — do not edit by hand. */

export const POST_LOCAL_IMAGE_POOL_GANGNAM: readonly string[] = ${JSON.stringify(gangnam.map((x) => x.url), null, 2)} as const;

export const POST_LOCAL_IMAGE_POOL_GWANGHWAMUN: readonly string[] = ${JSON.stringify(gwanghwamunAll, null, 2)} as const;
`;

  fs.writeFileSync(OUT, body, "utf8");
  console.log(
    `Wrote ${OUT} (${gangnam.length} gangnam, ${gwanghwamunAscii.length} gwanghwamun-ascii, ${gwanghwamunLegacy.length} gwanghwamun-legacy)`,
  );
}

main();
